"""Writes riscv_ae350_config.v from riscv_ae350_soc.ipc: the `define list that the RTL of the Gowin RiscV_AE350_SOC IP is compiled with (docs/P1_TOP.md section 2).

Why this exists: the IP generator in Gowin EDA for this block is a GUI dialog only (GowinModGen, the
command-line generator, knows only primitive IP such as PLL_ADV and answers "unknown model type" for
RiscV_AE350_SOC).  What the dialog produces is (a) this define file and (b) a synthesized,
encrypted netlist of the IP's own sources in IDE/ipcore/RiscV_AE350_SOC/data of the Gowin install.  gowin/p1/build.sh
instead adds those data sources to the chip project directly, with this define file on the
include path, so the IP is regenerated from the committed .ipc on every build with no GUI step.
The define names are the ones riscv_ae350_top.v tests (and that the IP DLL writes); the .ipc keys
are the dialog's own, so the same .ipc also opens in the GUI.

Two configurations exist (gowin/p1/build.sh, TR_DDR): riscv_ae350_soc.ipc has the data memory on the bus that comes out of
the block (1 GB through rtl/mem/ddr_mem.v), and riscv_ae350_soc_256.ipc uses the block's own shared DDR3
controller (256 MB, the fall-back).  A define that belongs to a switched-off option is not written:
DEFAULT_DDR3_SETTINGS only with ENABLE_DDR3, and the DDR3 address and data widths only in the shared read/write mode.

Usage: ipc_to_config.py <in.ipc> <out riscv_ae350_config.v>
Only the standard library is used, and the script reads the [Config] section of the .ipc file, which is a plain key=value list.
"""
import sys

MAP = [  # (ipc key, define, value-carrying)
    ("SpiFlashInstructionMemory", "AE350_EMB_SPIFLASH_EN", False),
    ("ENABLE_DDR3", "AE350_EMB_DDR3_EN", False),
    ("defaultDDR3Setttings", "DEFAULT_DDR3_SETTINGS", False),
    ("sharedDdr3RWMode", "AE350_DDR3_PL_RW_EN", False),
    # docs/MEM_1GB.md: "Customized Data Memory" (MUG1031 8.2.3): the data memory bus DDR_H* comes
    # out of the block. Key names as in Sipeed's ae350_customized_demo riscv_ae350_soc.ipc.
    ("ENABLE_CUSTOMIZED_DATA", "AE350_EXT_D_MEM_EN", False),
    ("ENABLE_EXTENDED_AHB_SLAVE", "AE350_EXT_AHB_SLAVE_EN", False),
    ("ENABLE_PLIC", "AE350_EXT_INT_EN", False),
    ("ENABLE_UART1", "AE350_APB_UART1_EN", False),
    ("ENABLE_UART2", "AE350_APB_UART2_EN", False),
    ("ENABLE_PIT", "AE350_APB_PIT_EN", False),
    ("ENABLE_WDT", "AE350_APB_WDT_EN", False),
    ("ENABLE_RTC", "AE350_APB_RTC_EN", False),
    ("ENABLE_GPIO", "AE350_APB_GPIO_EN", False),
    ("AddrWidth", "DDR3_RW_ADDR_WIDTH", True),
    ("DataWidth", "DDR3_RW_DATA_WIDTH", True),
]

# Read the [Config] section of the .ipc file into a dict (keys and values as text).
cfg = {}
section = None
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.strip()
    if line.startswith("["):
        section = line
    elif "=" in line and section == "[Config]":
        k, v = line.split("=", 1)
        cfg[k.strip()] = v.strip()

out = ["// GENERATED by gowin/p1/ip/ipc_to_config.py from riscv_ae350_soc.ipc -- do not edit",
       "// (docs/P1_TOP.md section 2). Define list for the RiscV_AE350_SOC IP sources."]
# A flag is written as `define NAME when its key is "true"; a value-carrying define is written with its value, and only when
# the shared DDR3 read/write mode is on, since the widths mean nothing otherwise.
shared = cfg.get("sharedDdr3RWMode") == "true"
for key, define, valued in MAP:
    v = cfg.get(key)
    if v is None:
        continue
    if valued:
        if shared:
            out.append("`define %s %s" % (define, v))
    elif v == "true":
        if define == "DEFAULT_DDR3_SETTINGS" and cfg.get("ENABLE_DDR3") != "true":
            continue
        out.append("`define %s" % define)
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
