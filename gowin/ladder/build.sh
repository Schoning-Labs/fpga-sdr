# Builds one step of the first-power-on ladder (docs/LADDER.md) with Gowin EDA Standard: three small bitstreams, each adding one
# part, so that a failed first power-on names the faulty part.
#   STEP=1  PLLs + AE350 + 1 GB DDR3 controller + serial port + LEDs + register page + clock counters
#   STEP=2  step 1 + HDMI color bars, 1080p60 (the DDR3 size probe and memory test belong to the program, fw/tr-ladder)
#   STEP=3  step 2 + a 1 kHz tone on the PT8211 DAC
# The script is cut down from gowin/p1/build.sh of this repository and keeps its IP regeneration, tool, device, defines, margin and
# verdict steps: top rtl/top/ladder_top.v, pins gowin/ladder/ladder.cst, timing gowin/ladder/ladder.sdc, the four PLLs of
# gowin/p1/ip, the 1 GB DDR3 path only (no TR_DDR=256 variant), no Ethernet and no sdr_core. gowin/p1/build.sh,
# sdr_top.v and the p1 constraint files are not touched by it.
#
# Usage, from the repository root:   STEP=1 OUT_DIR=<absolute> gowin/ladder/build.sh [--syn]
# Output: $OUT_DIR/ladder<STEP>/ladder_top/ ; bitstream impl/pnr/ladder_top.fs ; report impl/pnr/ladder_top_tr_content.html.
# Environment: STEP (1 to 3, default 1), OUT_DIR (absolute; default gowin/impl), GOWIN_IDE (the IDE folder; the default is the
# author's V1.9.12.04 install, as in gowin/p1/build.sh), GOWIN_PLACE_OPT (default 3, the value that measured best on this board;
# the full build's default is 1), GOWIN_ROUTE_OPT (default 1), TIMING_MARGIN_PCT (default 5: the design clocks are tightened by
# that many percent in the build's copy of the constraints) and GOWIN_DRY=1 (write the project and stop before Gowin starts).
# The process ID of gw_sh is written to <out>/gw_sh.pid, and after place-and-route tools/gowin_verdict.py prints the failing end
# points over all clock pairs.
#
# Needs Gowin EDA V1.9.12.04 (Standard, a licensed install) with its AE350 IP sources and GowinModGen.exe, Windows with
# powershell.exe (for the junctions into rtl/ and hw/) and Git Bash (cygpath, /proc), python, and git for the build identifier
# (00000000 without it). It does not touch the board; tools/ladder_fw.sh writes the bitstream and the program, and a board loader tool
# (board.py with its board.json, not part of this repository) loads the SRAM only (through run.bat for the full radio).
set -euo pipefail

# The IDE folder of the Gowin EDA install (the one that holds bin/gw_sh.exe): the default is the author's, so set GOWIN_IDE to yours.
GOWIN_IDE="${GOWIN_IDE:-/c/Gowin/Gowin_V1.9.12.04_x64/IDE}"
GOWIN_SH="$GOWIN_IDE/bin/gw_sh.exe"
MODGEN="$GOWIN_IDE/bin/GowinModGen.exe"
AE350_DATA="$GOWIN_IDE/ipcore/RiscV_AE350_SOC/data"
DEVICE_PN="GW5AST-LV138FPG676AC1/I0"
DEVICE_NAME="GW5AST-138C"
DEVICE_VERSION="B"
TOP="ladder_top"

# STEP chooses which of the three bitstreams is built; it also selects the sources and defines below.
STEP="${STEP:-1}"
case "$STEP" in 1|2|3) ;; *) echo "error: STEP must be 1, 2 or 3" >&2; exit 1 ;; esac
repo="$(pwd -W 2>/dev/null || pwd)"
if [ ! -f "$repo/gowin/ladder/build.sh" ]; then
    echo "error: run from the repository root" >&2
    exit 1
fi
mode="all"
[ "${1:-}" = "--syn" ] && mode="syn"

out="${OUT_DIR:-$repo/gowin/impl}/ladder${STEP}/${TOP}"
rm -rf "${out:?}"
mkdir -p "$out/ip"

# ---------------------------------------------------------------- IP regeneration
python "$repo/gowin/p1/ip/ipc_to_config.py" "$repo/gowin/p1/ip/riscv_ae350_soc.ipc" "$out/ip/riscv_ae350_config.v"
for name in gowin_pll_ae350.mod gowin_pll_ddr3.mod gowin_pll_dsp.mod gowin_pll_video.mod; do
    sed "s#@OUT@#$(cygpath -m "$out/ip")#" "$repo/gowin/p1/ip/$name" > "$out/ip/$name"
    ( cd "$out/ip" && "$MODGEN" -do "$name" ) > "$out/ip/${name%.mod}.log" 2>&1 || {
        echo "GowinModGen failed for $name, see $out/ip/${name%.mod}.log" >&2; exit 1; }
done

# ---------------------------------------------------------------- build identifier, defines
hash="$(git -C "$repo" rev-parse --short=8 HEAD 2>/dev/null || echo 00000000)"
cat > "$out/tr_build_id.v" <<EOF
// generated by gowin/ladder/build.sh: first 8 hex digits of the commit this bitstream was built from
module tr_build_id (output wire [31:0] id);
    assign id = 32'h${hash};
endmodule
EOF
# the first source file carries the defines, which stay in force for the files after it (one compilation unit)
{
    echo "// generated by gowin/ladder/build.sh"
    echo '`define GW_IDE        // rtl/vendor/hdmi/serializer.sv: Gowin OSER10 serializers'
    echo "\`define LADDER_STEP $STEP"
    [ "$STEP" -lt 2 ] || echo '`define LADDER_VIDEO'
    [ "$STEP" -lt 3 ] || echo '`define LADDER_AUDIO'
} > "$out/ladder_defines.v"

# Junctions so the repo-root-relative paths in the RTL resolve from the project directory
src="$repo"
powershell.exe -NoProfile -Command \
    "New-Item -ItemType Junction -Path '$(cygpath -w "$out/rtl")' -Target '$(cygpath -w "$repo/rtl")' | Out-Null; \
     New-Item -ItemType Junction -Path '$(cygpath -w "$out/hw")' -Target '$(cygpath -w "$repo/hw")' | Out-Null"

# ---------------------------------------------------------------- sources
rtl=(rtl/mem/ddr_mem.v rtl/top/ladder_cnt_x.v rtl/top/ladder_regs.v)
sv=()
if [ "$STEP" -ge 2 ]; then
    rtl+=(rtl/video/colorbar_gen.v rtl/top/ladder_bars.v)
    sv=(
        rtl/vendor/hdmi/tmds_channel.sv rtl/vendor/hdmi/serializer.sv rtl/vendor/hdmi/packet_picker.sv
        rtl/vendor/hdmi/packet_assembler.sv rtl/vendor/hdmi/audio_clock_regeneration_packet.sv
        rtl/vendor/hdmi/audio_info_frame.sv rtl/vendor/hdmi/audio_sample_packet.sv
        rtl/vendor/hdmi/auxiliary_video_information_info_frame.sv
        rtl/vendor/hdmi/source_product_description_info_frame.sv rtl/vendor/hdmi/hdmi.sv
    )
fi
[ "$STEP" -lt 3 ] || rtl+=(rtl/top/ladder_pt8211.v)
rtl+=(rtl/top/ladder_top.v)
# the AE350 without its own DDR3 controller; the DDR3 IP's source (the copy in the AE350's folder) is instantiated
# by rtl/mem/ddr_mem.v, with our settings in hw/gowin/mem
ip_src=(riscv_ae350_top.v riscv_ae350_soc.v riscv_ae350_flash.v ddr3_1_4code_hs.v DDR3_TOP.v)
ddr_inc="$src/hw/gowin/mem"

cp "$repo/gowin/ladder/ladder.cst" "$out/ladder.cst"
# the build's copy of the constraints; step 1 has no video unit, so the false paths into its serializers have no pins
cp "$repo/gowin/ladder/ladder.sdc" "$out/ladder_all.sdc"
[ "$STEP" -ge 2 ] || sed -i '/serializer/d' "$out/ladder_all.sdc"
# Timing margin: the design clocks are tightened by TIMING_MARGIN_PCT percent, in the build's copy of the constraints only.
mpct="${TIMING_MARGIN_PCT:-5}"
[ "$mpct" = 0 ] || python "$repo/gowin/p1/sdc_margin.py" "$out/ladder_all.sdc" "$mpct"

# The Tcl script for gw_sh: project, device, sources, constraints, options and the run command.
tcl="$out/run.tcl"
{
    echo "create_project -name ${TOP} -dir {$(cygpath -m "$(dirname "$out")")} -pn ${DEVICE_PN} -device_version ${DEVICE_VERSION} -force"
    echo "set_device -name ${DEVICE_NAME} ${DEVICE_PN}"
    echo "add_file -type verilog {$(cygpath -m "$out/ladder_defines.v")}"
    for f in "${rtl[@]}" ${sv[@]+"${sv[@]}"}; do echo "add_file -type verilog {$(cygpath -m "$src/$f")}"; done
    for f in "$out"/ip/gowin_pll_*.v; do
        case "$f" in *_tmp.v) ;; *) echo "add_file -type verilog {$(cygpath -m "$f")}" ;; esac
    done
    for f in "${ip_src[@]}"; do echo "add_file -type verilog {$(cygpath -m "$AE350_DATA/$f")}"; done
    echo "add_file -type verilog {$(cygpath -m "$out/tr_build_id.v")}"
    echo "add_file -type cst {$(cygpath -m "$out/ladder.cst")}"
    echo "add_file -type sdc {$(cygpath -m "$out/ladder_all.sdc")}"
    echo "set_option -top_module ${TOP}"
    echo "set_option -include_path {$(cygpath -m "$out");$(cygpath -m "$out/ip");$(cygpath -m "$AE350_DATA");$(cygpath -m "$ddr_inc")}"
    echo "set_option -verilog_std sysv2017"
    echo "set_option -looplimit 20000"
    echo "set_option -use_cpu_as_gpio 1"
    echo "set_option -use_mspi_as_gpio 1"
    echo "set_option -use_sspi_as_gpio 1"
    echo "set_option -place_option ${GOWIN_PLACE_OPT:-3}"
    echo "set_option -route_option ${GOWIN_ROUTE_OPT:-1}"
    echo "set_option -timing_driven 1"
    echo "set_option -gen_posp 1"
    # V1.9.12.04 always writes the text timing report and no longer knows this switch; V1.9.11 needs it.
    case "$GOWIN_IDE" in *1.9.11*) echo "set_option -gen_text_timing_rpt 1" ;; esac
    echo "run ${mode}"
} > "$tcl"

if [ "${GOWIN_DRY:-0}" = 1 ]; then
    echo "gowin/ladder/build.sh: dry run, project written to $out (run.tcl, ladder_all.sdc); Gowin not started"
    exit 0
fi
log="$out/gw_sh.log"
start=$(date +%s)
# gw_sh runs as a child so its Windows process ID can be written down (tools/gowin_watch.py)
( cd "$out" && exec "$GOWIN_SH" run.tcl ) > "$log" 2>&1 &
gwpid=$!
cat "/proc/$gwpid/winpid" > "$out/gw_sh.pid" 2>/dev/null || echo "$gwpid" > "$out/gw_sh.pid"
if ! wait "$gwpid"; then
    echo "gowin/ladder/build.sh: step $STEP: Gowin run failed after $(( $(date +%s) - start )) s, see $log" >&2
    tail -40 "$log" >&2
    exit 1
fi
echo "gowin/ladder/build.sh: step $STEP ${mode} done in $(( $(date +%s) - start )) s; reports in $out/impl"
if [ "$mode" = all ]; then
    python "$repo/tools/gowin_verdict.py" "$out/impl/pnr/${TOP}_tr_content.html" || true
fi
