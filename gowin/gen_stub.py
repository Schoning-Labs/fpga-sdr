"""Writes register stubs for measuring a large block's own top-level logic without its sub-blocks (gowin/reports/README.md, "rx_backend").

For each named module it writes a module of the same name and ports whose inside is only registers: every input bit is
captured into a register each clock, and every output bit is driven from a register (a shift chain fed with the XOR of all
captured inputs, so nothing is constant and nothing is optimized away).  Put the stub file in place of the real sub-block
files and the surrounding logic is timed register to register at every sub-block boundary, which is what the real
sub-blocks give it too (their outputs are registers, and their inputs end in registers within the sub-block's first
stage), except where a real sub-block has a combinational input-to-output path, which the report must then say.

Parameters: the stubs accept (and ignore) the parameters the real modules are instantiated with in this repository
(HB_FILE, LOG2_FILE, EXP2_FILE, ADDR_WIDTH); port widths come from yosys with the real module's default parameters,
so yosys (oss-cad-suite, C:/tools/oss-cad-suite on the author's PC) has to be on the PATH.

Usage, from the repository root: gowin/gen_stub.py <out.v> --modules m1,m2,... --clk clk <file.v> ...
The --modules list names the modules to stub, --clk the clock port (default clk), and the files are the Verilog sources in
which yosys finds them.
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile


def ports_of(top, files):
    """The ports of module `top` as (name, direction, width) tuples, as yosys elaborates it from `files`."""
    with tempfile.TemporaryDirectory() as td:
        js = os.path.join(td, "p.json").replace("\\", "/")
        script = "".join(f"read_verilog -sv {f}; " for f in files)
        script += f"hierarchy -top {top}; proc; write_json {js}"
        r = subprocess.run(["yosys", "-q", "-p", script], capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stdout + r.stderr)
            sys.exit(f"gen_stub: yosys could not read {top}")
        with open(js) as fh:
            mod = json.load(fh)["modules"][top]
    return [(n, p["direction"], len(p["bits"])) for n, p in mod["ports"].items()]


def main():
    """Writes the stub file: for each module one register stub (input register, output shift chain) and a line of statistics."""
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--modules", required=True)
    ap.add_argument("--clk", default="clk")
    ap.add_argument("files", nargs="+")
    a = ap.parse_args()
    L = ["// Generated by gowin/gen_stub.py (see that file's header); not hand-edited.",
         "`timescale 1ns / 1ps"]
    for m in a.modules.split(","):
        ports = ports_of(m, a.files)
        ins = [(n, w) for n, d, w in ports if d == "input" and n != a.clk]
        outs = [(n, w) for n, d, w in ports if d == "output"]
        in_bits = sum(w for _, w in ins)
        out_bits = sum(w for _, w in outs)
        L.append(f"module {m} #(parameter HB_FILE = \"\", parameter LOG2_FILE = \"\", "
                 f"parameter EXP2_FILE = \"\", parameter integer ADDR_WIDTH = 32) (")
        decl = [f"    input  wire {a.clk}"]
        for n, w in ins:
            decl.append(f"    input  wire [{w - 1}:0] {n}")
        for n, w in outs:
            decl.append(f"    output wire [{w - 1}:0] {n}")
        L.append(",\n".join(decl))
        L.append(");")
        L.append(f"    reg [{in_bits - 1}:0] stub_in_q;")
        L.append(f"    always @(posedge {a.clk}) stub_in_q <= {{{', '.join(n for n, _ in ins)}}};")
        L.append(f"    reg [{out_bits - 1}:0] stub_out_q;")
        if out_bits > 1:
            L.append(f"    always @(posedge {a.clk}) stub_out_q <= {{stub_out_q[{out_bits - 2}:0], ^stub_in_q}};")
        else:
            L.append(f"    always @(posedge {a.clk}) stub_out_q <= ^stub_in_q;")
        pos = 0
        for n, w in outs:
            L.append(f"    assign {n} = stub_out_q[{pos + w - 1}:{pos}];")
            pos += w
        L.append("endmodule")
        print(f"gen_stub: {m}: {in_bits} input bits, {out_bits} output bits")
    with open(a.out, "w", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
