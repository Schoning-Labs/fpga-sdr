//! Trap entry that keeps the FPU out of every trap handler. No interrupt or exception handler in
//! this firmware may touch the floating-point registers (`docs/ARCHITECTURE.md` 5.3: no handler
//! needs the FPU), because a handler that did would silently corrupt the floating-point state of the
//! interrupted task. A guard that every handler had to open by hand as its first statement would
//! do nothing for a handler that forgot it, so the protection sits in `_start_trap`, the single
//! entry point every trap in this firmware goes through. It forces `mstatus.FS` to Off before any
//! handler runs and restores the value from before the trap afterwards, for every interrupt and
//! every exception, and no handler can opt out of it or leave it out by accident.
//!
//! # Why `_start_trap` itself is overridden
//!
//! The `link.x.in` of `riscv-rt` provides `_start_trap` as a linker-script `PROVIDE` that defaults
//! to its own `_default_start_trap` (generated by `RiscvArch::default_start_trap` in riscv-macros)
//! unless the final binary defines a strong symbol of that name, which is what the `global_asm!`
//! block below does. `_setup_interrupts` of `riscv-rt` (the `mtvec` setup that runs once at
//! start-up) points the trap vector at whatever `_start_trap` resolves to, so this is the one real
//! hardware trap entry. The workspace does not enable the `v-trap` feature of `riscv-rt` (`fw/
//! tr-app/Cargo.toml` only has `single-hart`), so it runs in direct mode, where every interrupt and
//! every exception lands here and is passed on to `_start_trap_rust`, which reads `mcause` and calls
//! `_dispatch_core_interrupt` or `_dispatch_exception`. Wrapping this one entry point therefore
//! wraps both kinds of trap with a single piece of code.
//!
//! # What it does, and why FS needs an explicit save and restore
//!
//! `mret` only swaps `mstatus.MIE`, `MPIE` and `MPP` (RISC-V privileged spec), and `FS` is left
//! alone by a trap return. If this code forced FS to Off on entry and left it there, the interrupted
//! task would resume with FS Off even if it had floating-point work in flight (Initial, Clean or
//! Dirty) and its very next floating-point instruction would trap for no reason. So the FS bits go
//! into an extra stack slot first (one word more than the 16-word integer frame of `riscv-rt`,
//! padded to keep the frame 16-byte aligned) and come back from there after `_start_trap_rust`
//! returns, before the integer registers are reloaded and before `mret`. An interrupt handler and
//! an exception handler take the same path, because `#[exception(...)]` handlers may return `()`
//! and fall through the same shared restore code back to `mret`.
//!
//! # Cost
//!
//! Six extra integer instructions per trap compared with the stock `_default_start_trap` (on
//! entry: load the FS mask, read, mask and store `mstatus`, clear FS; on exit: reload the mask,
//! then clear and set `mstatus` from the saved value), plus one extra 4-byte stack slot padded to
//! 16 bytes. No floating-point register is read or written. Saving and restoring the caller-saved
//! ones instead (`ft0` to `ft7`, `fa0` to `fa7` and `ft8` to `ft11`, which is 20 registers and 40
//! `fsd` and `fld` instructions of 8 bytes each) was rejected in `docs/C1_AE350.md` as a permanent
//! cost for a case that the design of this firmware never creates.
//!
//! # Test
//!
//! `fw/tr-app/src/bin/qemu_c4.rs` and `tools/qemu_c4.sh` run an f64 loop in the main task and check
//! that its result is bit-identical whether or not a real machine-timer interrupt fires repeatedly
//! during it, and separately whether or not a real, deliberately triggered and recoverable
//! breakpoint exception does. A handler that uses the FPU anyway is caught as an illegal
//! instruction, with no code in the handler asking for that protection.

#[cfg(any(target_arch = "riscv32", target_arch = "riscv64"))]
core::arch::global_asm!(
    r#"
.section .trap.start, "ax"
.balign 4
.global _start_trap
_start_trap:
    addi sp, sp, -80
    sw ra,   0*4(sp)
    sw t0,   1*4(sp)
    sw t1,   2*4(sp)
    sw t2,   3*4(sp)
    sw t3,   4*4(sp)
    sw t4,   5*4(sp)
    sw t5,   6*4(sp)
    sw t6,   7*4(sp)
    sw a0,   8*4(sp)
    sw a1,   9*4(sp)
    sw a2,  10*4(sp)
    sw a3,  11*4(sp)
    sw a4,  12*4(sp)
    sw a5,  13*4(sp)
    sw a6,  14*4(sp)
    sw a7,  15*4(sp)

    // Save mstatus.FS (bits [14:13], mask 0x6000) at offset 64, then force it Off for the whole
    // handler call so that no handler can touch the FPU: enforced here, unconditionally,
    // rather than trusted to per-handler convention.
    lui  t1, 0x6
    csrr t0, mstatus
    and  t0, t0, t1
    sw   t0, 16*4(sp)
    csrc mstatus, t1

    add  a0, sp, zero
    jal  ra, _start_trap_rust

    // Restore mstatus.FS to exactly what it was on entry -- needed whether _start_trap_rust just
    // dispatched an interrupt or an exception (both return here the same way, see this file's
    // module doc), and must happen before `mret`, which does not restore FS itself.
    lui  t1, 0x6
    lw   t0, 16*4(sp)
    csrc mstatus, t1
    csrs mstatus, t0

    lw ra,   0*4(sp)
    lw t0,   1*4(sp)
    lw t1,   2*4(sp)
    lw t2,   3*4(sp)
    lw t3,   4*4(sp)
    lw t4,   5*4(sp)
    lw t5,   6*4(sp)
    lw t6,   7*4(sp)
    lw a0,   8*4(sp)
    lw a1,   9*4(sp)
    lw a2,  10*4(sp)
    lw a3,  11*4(sp)
    lw a4,  12*4(sp)
    lw a5,  13*4(sp)
    lw a6,  14*4(sp)
    lw a7,  15*4(sp)
    addi sp, sp, 80
    mret
"#
);
