"""Quarter-wave sine table for the numerically controlled oscillator (NCO) mixer rtl/rx/nco_mixer.v (docs/ARCHITECTURE.md).

The mixer multiplies the incoming samples by a sine and a cosine of the tuning frequency, and it reads both from this one table
of a quarter of a sine wave, since the other three quarters are mirror images.  The script writes the table for the Verilog
(two files: the .hex file for simulation and a ready made Gowin block RAM module for the chip) and the Rust model reads the
same .hex file.  Run from anywhere: python tools/gen_nco_table.py (standard library only).

Table T[k] = round(A * sin((k + 0.5) * pi / 2048)), k = 0..1023, 18 bits (all positive, below
2^17). Written to rtl/rx/nco_sin_table.hex ($readmemh, hex, one word per line) as 512 words of
36 bits, word j = {T[j], T[1023 - j]}: one single-port 512 x 36 ROM, which is one 18-kbit block
RAM (a 1,024 x 18 ROM read through two ports becomes two ROMs in Gowin synthesis); the mixer
reads word min(k, 1023 - k) and swaps the halves for k >= 512.

- The half-entry offset puts sample k at the center of the k-th 1/4096 of a turn, so the same
  table read at address 1023 - k gives the cosine of the same angle (cos x = sin(pi/2 - x)): one
  read gives sine and cosine each clock, and the first-order Taylor correction
  (sin(a + d) = sin a + d cos a) works on a residual d of at most half a step either side.
- A = 107,922 sets the mixer's gain to A / 2048 = 52.6963, which is 32 times the CORDIC gain 1.646760
  (measured on the RTL: 52.6963), so every level downstream of the mixer is the same as a CORDIC
  mixer would give. All entries are positive and below 2^17.

The Rust model (fw/tr-rxmodel/src/nco.rs) reads this same file at compile time, so the RTL and
the model can never use different tables.
"""
import math
import os

N = 1024   # entries in the quarter wave (4096 steps per turn)
A = 107922  # amplitude, see the gain note above
# The two output files, found from the script's own location: the .hex table, and the Gowin block RAM module.
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "rx", "nco_sin_table.hex")
OUT_VH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "rx", "nco_sin_dp.vh")


def table():
    """The N table entries T[k] = round(A sin((k + 0.5) pi / 2N)), the 0.5 putting each sample in the middle of its step."""
    return [int(round(A * math.sin((k + 0.5) * math.pi / (2 * N)))) for k in range(N)]


def dp_module(t):
    """The text of rtl/rx/nco_sin_dp.vh: module nco_sin_dp as one Gowin DPX9B (true dual-port 18-kbit block RAM, 1,024 x 18,
    both ports read-only), included by nco_mixer.v under `GOWIN_DSP.  Gowin's block RAM primitive takes its contents as
    64 initialization words of 288 bits each: INIT_RAM_i holds words 16 i .. 16 i + 15 of the table, and word k sits at
    bits 18 (k mod 16) +: 18 of it (as the simulation model prim_sim.v lays it out, ram_MEM bit 18 k)."""
    o = []
    o.append("// SPDX-License-Identifier: Apache-2.0")
    o.append("// Copyright 2026 Franz Schöning, https://www.schoning.com")
    o.append("// GENERATED by tools/gen_nco_table.py -- do not edit; change the generator.")
    o.append("//")
    o.append("// nco_sin_dp for the Gowin builds (`GOWIN_DSP): the quarter-wave table T[k] (rtl/rx/nco_sin_table.hex")
    o.append("// holds the same values as 512 x 36) as one dual-port block RAM, 1,024 x 18, both ports read-only")
    o.append("// (UG300 DPX9B, bypass read mode: a registered read, the data of the address taken at the clock edge, held")
    o.append("// while ce is low). Port a reads aa, port b ab. One 18-kbit block, where the 512 x 36 single-port ROM it")
    o.append("// replaces is counted as two by place-and-route.")
    o.append("module nco_sin_dp #(parameter TABLE_FILE = \"\") (")
    o.append("  input         clock, ce,")
    o.append("  input  [9:0]  aa, ab,")
    o.append("  output [17:0] qa, qb")
    o.append(");")
    o.append("  DPX9B #(.READ_MODE0(1'b0), .READ_MODE1(1'b0), .WRITE_MODE0(2'b00), .WRITE_MODE1(2'b00),")
    o.append("          .BIT_WIDTH_0(18), .BIT_WIDTH_1(18), .BLK_SEL_0(3'b000), .BLK_SEL_1(3'b000), .RESET_MODE(\"SYNC\"),")
    for i in range(64):
        v = 0
        for w in range(16):
            v |= t[16 * i + w] << (18 * w)
        sep = "," if i < 63 else ")"
        o.append(f"          .INIT_RAM_{i:02X}(288'h{v:072x}){sep}{' u0 (' if i == 63 else ''}")
    o.append("      .DOA(qa), .DOB(qb), .DIA(18'd0), .DIB(18'd0), .BLKSELA(3'b000), .BLKSELB(3'b000),")
    o.append("      .ADA({aa, 4'b0000}), .ADB({ab, 4'b0000}), .WREA(1'b0), .WREB(1'b0),")
    o.append("      .CLKA(clock), .CLKB(clock), .CEA(ce), .CEB(ce), .OCEA(1'b1), .OCEB(1'b1), .RESETA(1'b0), .RESETB(1'b0));")
    o.append("endmodule")
    return "\n".join(o) + "\n"


def main():
    """Builds the table, checks that every entry fits and that the mirror entry really is the cosine, and writes both files."""
    t = table()
    assert all(0 < v < (1 << 17) for v in t)
    # cos of the same angle is the mirrored entry
    for k in range(N):
        assert abs(t[N - 1 - k] - A * math.cos((k + 0.5) * math.pi / (2 * N))) <= 0.5 + 1e-9
    # 512 words of 36 bits: the entry j in the upper half and its mirror entry N-1-j in the lower half, which is what one
    # read of the single block RAM has to deliver (sine and cosine of the same angle).
    with open(OUT, "w", newline="\n") as f:
        for j in range(N // 2):
            f.write(f"{(t[j] << 18) | t[N - 1 - j]:09x}\n")
    with open(OUT_VH, "w", newline="\n") as f:
        f.write(dp_module(t))
    print(f"wrote {os.path.normpath(OUT_VH)}")
    print(f"wrote {os.path.normpath(OUT)}: {N // 2} x 36 bit ({N} x 18-bit entries), A = {A}, "
          f"gain A/2048 = {A / 2048:.6f}")


if __name__ == "__main__":
    main()
