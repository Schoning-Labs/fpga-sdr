# Checks the FT8 spectrogram frame core (rtl/ft8/ft8_frame_core.v and ft8_power.v, docs/F5_FT8SPEC.md) against every frame of a
# real WSJT-X sample recording (default captures/ft8/qso3_busy.wav), bit for bit against the fixed-point Rust FT8 model
# (docs/S15_FT8MODEL.md). The pattern is the one of tools/qemu_s15.sh --smoke and of the receiver-bank check in tools/check.sh:
# build the host reference tool, generate the vectors this needs, run an iverilog testbench over them, and skip without
# failing (instead of erroring) when captures/ has not been fetched (tools/fetch_test_audio.sh) or fw/ is not present.
#
# Runtime: the whole 372-frame recording takes about 20 minutes in Icarus (tens of thousands of clocks per frame).
# FT8_WAV_FRAMES picks how many of the 372 frames to check, spread evenly across the slot (default all of them);
# tools/check.sh runs this with 20.
#
# Usage: bash tools/check_ft8_wav.sh [wav path]   (default captures/ft8/qso3_busy.wav)
#        FT8_WAV_FRAMES=<n> bash tools/check_ft8_wav.sh   (check n frames spread across the slot instead of all 372)
# Needs iverilog and vvp on PATH (oss-cad-suite) and cargo, which builds the host tool ft8-frontend. No Gowin EDA, no board.

set -uo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

wav="${1:-captures/ft8/qso3_busy.wav}"
if [ ! -f "$wav" ]; then
    echo "SKIPPED check_ft8_wav.sh: $wav not fetched; skipping (tools/fetch_test_audio.sh)"
    exit 0
fi
if [ ! -d fw ]; then
    echo "SKIPPED check_ft8_wav.sh: fw/ not found; skipping" >&2
    exit 0
fi
if ! command -v iverilog >/dev/null 2>&1; then
    echo "SKIPPED check_ft8_wav.sh: iverilog not found on PATH; skipping" >&2
    exit 0
fi

# Repo-relative paths throughout, because the simulator (the iverilog of oss-cad-suite) is a native Windows program and cannot
# open MSYS-style /g/... paths.
vec_dir="sim/ft8/out/vectors"
mkdir -p "$vec_dir"

echo "== building ft8-frontend (host) ==" >&2
(cd fw && cargo build -q --release -p tr-modes --bin ft8-frontend) || { echo "FAIL: host build"; exit 1; }
# The host tool is built in release mode; on Windows cargo names it ft8-frontend.exe.
host_tool="fw/target/release/ft8-frontend"
[ -x "$host_tool.exe" ] && host_tool="$host_tool.exe"

echo "== generating vectors from $wav ==" >&2
"$host_tool" vectors "$wav" "$vec_dir" >&2 || { echo "FAIL: vectors"; exit 1; }

n_frames="${FT8_WAV_FRAMES:-372}"
out="sim/ft8/out/tb_ft8_frame_core_wav_gen.v"
mkdir -p "$(dirname "$out")"

# Write the small parameter file that the committed harness sim/ft8/ft8_frame_core_wav_harness.v includes (through the
# FT8_WAV_PARAMS define): it says how many of the 372 frames to check and where the vector files are. It is generated and not committed.
cat > "$out.frames" <<EOF
// Generated by tools/check_ft8_wav.sh -- not committed.
localparam integer N_TIME    = 372;
localparam integer N_CHECK   = $n_frames;
localparam AUDIO_FILE  = "$vec_dir/audio.hex";
localparam POWER_FILE  = "$vec_dir/spectrogram_sh16.hex";
EOF

echo "== running sim/ft8/ft8_frame_core_wav_harness.v ($n_frames of $((372)) frames) ==" >&2
if ! iverilog -g2012 -DFT8_WAV_PARAMS=\"$out.frames\" -o "$out.vvp" sim/ft8/ft8_frame_core_wav_harness.v; then
    echo "FAIL: compile"
    exit 1
fi
output="$(vvp "$out.vvp")"
status=$?
echo "$output"
if [ "$status" -ne 0 ] || ! grep -q "PASS" <<<"$output"; then
    echo "FAIL: check_ft8_wav.sh"
    exit 1
fi
echo "PASS: check_ft8_wav.sh"
