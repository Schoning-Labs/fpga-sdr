"""
Generates the targeted alias-rejection test signal: one full-scale (0 dBFS) CW
interferer placed exactly at the worst-case alias frequency computed by
tools/analyze_alias.py, for each of the 4 output rates and each of the two
decimating stages that can alias (cic_fixed, cic_var), which makes 8 cases in total.

Each case gets its own isolated time segment in the ADC file (only that
one tone is present), so that no receiver can pick up another case's interferer.
This matters because several of these worst-case frequencies are only tens of
kHz apart, and a wide-passband (384 ksps) receiver would otherwise also
catch the interferer meant for a narrower-rate receiver.

The receiver under test is tuned to phase_inc=0 (baseband/DC) for every
case: the interferer sits far from the receiver's own passband, and
whatever leaks through -- the alias -- lands near DC, which is exactly
what sim/check_alias.py looks for.

Run, in this order (works from any folder, the paths are found from the script's location; needs numpy):
    python tools/analyze_alias.py            (writes alias_plan.json)
    python tools/gen_signals/gen_alias_test_signals.py
Writes:
    tools/gen_signals/out/alias_test.hex  -- ADC samples ($readmemh)
    sim/alias_config.vh                   -- segment boundaries + receiver
                                              config for sim/tb_alias.v
"""
import json
import os

import numpy as np

FS_ADC = 76.8e6
# a hair under full scale (2047) so floating-point rounding at the cosine
# peaks never clips -- clipping would add odd-harmonic distortion that
# could itself land somewhere and confuse this measurement
ADC_FULL_SCALE = 2040.0  # ~ -0.03 dBFS, effectively full scale

# settle+measure length per segment, in "output points" at that receiver's
# rate (the filters settle within about 15 to 20 output samples, and 24
# leaves margin). Each disabled receiver's channel reset (chan_rst = rst | ~enable,
# see rx_channel.v) is held for its entire idle time, which costs real iverilog
# simulation time even though nothing changes, so the total sample count here
# directly drives the run time of the simulation and is kept as small as the settling allows.
SETTLE_OUTPUT_POINTS = 24
# Total decimation from the 76.8 MHz input to each output rate (cic_fixed 10 x cic_var x fir_decim 4).
TOTAL_DECIM = {48e3: 1600, 96e3: 800, 192e3: 400, 384e3: 200}

HERE = os.path.dirname(os.path.abspath(__file__))
PLAN_PATH = os.path.join(HERE, "out", "alias_plan.json")
HEX_PATH = os.path.join(HERE, "out", "alias_test.hex")
VH_PATH = os.path.normpath(os.path.join(HERE, "..", "..", "sim", "alias_config.vh"))

# The 2-bit rate select the receiver takes for each output rate.
RATE_CODE = {48e3: 0, 96e3: 1, 192e3: 2, 384e3: 3}


def main():
    """Reads the alias plan, builds one segment per case and writes the sample file, the Verilog config and the metadata."""
    with open(PLAN_PATH) as f:
        plan = json.load(f)

    # 8 cases: (receiver_index, rate, stage, freq_hz, predicted_landing_offset_hz)
    cases = []
    rx = 0
    for rate_str in ("48000", "96000", "192000", "384000"):
        entry = plan["rates"][rate_str]
        rate = entry["rate_hz"]
        for stage in ("cic1", "cic2"):
            cases.append({
                "rx": rx,
                "rate": rate,
                "stage": stage,
                "freq_hz": entry[f"{stage}_worst_freq_hz"],
                "predicted_db": entry[f"{stage}_worst_db"],
                "landing_offset_hz": entry[f"{stage}_landing_offset_hz"],
            })
            rx += 1

    segments = []
    x_all = []
    t_offset_samples = 0
    for c in cases:
        n_samples = SETTLE_OUTPUT_POINTS * TOTAL_DECIM[c["rate"]]
        t = np.arange(n_samples) / FS_ADC
        x = ADC_FULL_SCALE * np.cos(2 * np.pi * c["freq_hz"] * t)
        x_all.append(x)
        c["start_sample"] = t_offset_samples
        c["n_samples"] = n_samples
        t_offset_samples += n_samples
        segments.append(c)

    x_full = np.concatenate(x_all)
    xq = np.clip(np.round(x_full), -2048, 2047).astype(np.int32)
    clipped = int(np.sum((xq == 2047) | (xq == -2048)))

    os.makedirs(os.path.dirname(HEX_PATH), exist_ok=True)
    with open(HEX_PATH, "w") as f:
        for v in xq:
            f.write(f"{int(v) & 0xFFF:03x}\n")

    with open(VH_PATH, "w") as f:
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("// Copyright 2026 Franz Schöning, https://www.schoning.com\n")
        f.write("// Generated by tools/gen_signals/gen_alias_test_signals.py -- do not edit by hand.\n")
        f.write(f"localparam ALIAS_N_SAMPLES = {t_offset_samples};\n")
        for c in segments:
            rx = c["rx"]
            f.write(f"localparam ALIAS_RX{rx}_START = {c['start_sample']};\n")
            f.write(f"localparam ALIAS_RX{rx}_LEN   = {c['n_samples']};\n")
            f.write(f"localparam [1:0] ALIAS_RX{rx}_RATE_SEL = 2'd{RATE_CODE[c['rate']]}; "
                    f"// {c['rate']/1e3:.0f} ksps, {c['stage']}\n")

    plan_out = {"cases": segments, "total_samples": t_offset_samples, "fs_adc": FS_ADC}
    with open(os.path.join(HERE, "out", "alias_test_meta.json"), "w") as f:
        json.dump(plan_out, f, indent=2)

    print(f"Wrote {t_offset_samples} samples ({t_offset_samples/FS_ADC*1e3:.2f} ms) to {HEX_PATH}")
    print(f"Config header written to {VH_PATH}")
    print(f"Clipped samples: {clipped}")
    for c in segments:
        print(f"  rx{c['rx']}: {c['rate']/1e3:.0f}ksps {c['stage']:5s} "
              f"f={c['freq_hz']/1e6:.4f}MHz predicted={c['predicted_db']:.1f}dB "
              f"landing_offset={c['landing_offset_hz']:+.0f}Hz "
              f"[{c['start_sample']}:{c['start_sample']+c['n_samples']}]")


if __name__ == "__main__":
    main()
