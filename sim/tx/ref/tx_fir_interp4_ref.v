// Reference copy of rtl/tx/tx_fir_interp4.v as it was before the FIR was rebuilt to share one multiplier over
// time, renamed to tx_fir_interp4_ref so that it can be compiled next to the real module. It is kept only so
// that sim/tx/tb_tx_chain_rb2_equiv.v can check that the one-multiplier redesign gives a bit exact identical
// output stream, and is not meant to be used anywhere else; the real module is rtl/tx/tx_fir_interp4.v.
//
// What it models: stage 1 of the transmit chain (docs/ARCHITECTURE.md section 3.6), a polyphase FIR
// interpolator that takes 48 kHz complex baseband to 192 kHz, a factor of 4. It suppresses the images that the
// zero stuffing of the interpolation creates and, because the passband (+-12 kHz) is tiny next to the input
// rate of the CIC interpolator that follows, it needs no separate droop compensation (the measured CIC droop at
// 12 kHz is 0.28 dB, see docs/X1_TX.md). A polyphase filter splits the long lowpass into 4 short ones (phases),
// each of which is applied to the same sample history and gives one of the 4 output samples per input sample.
// This reference does all 10 multiply-adds of a phase, for I and for Q, in a single clock, which costs 20
// multipliers; the real module takes more clocks and uses one.
//
// Coefficients: rtl/tx/fir_coeffs.vh, 40 taps (10 taps per phase), generated by tools/design_tx_fir.py
// (Parks-McClellan, passband 0 to 12 kHz, stopband from 36 kHz, signed Q17). The same real-valued lowpass
// is applied to I and to Q.
//
// Protocol (modeled on the handshake of the HL2's FirInterp8_1024.v, simplified because there is no
// coefficient or sample block RAM and everything is small enough for registers):
//   - calc pulses once per output sample wanted, which is 4 pulses per input sample.
//   - req pulses for one clock, on the same edge on which the 4th (last) phase of an input sample is
//     produced, to ask for the next 48 kHz sample; x_real and x_imag must hold the new sample by the time
//     calc next pulses at phase 0, which is at least 3 clocks later.

`timescale 1ns / 1ps

module tx_fir_interp4_ref #(
    parameter IBITS = 16,
    parameter OBITS = 20,
    parameter COEFW = 18,
    parameter NP    = 10    // taps per phase (fir_coeffs.vh: NUMTAPS/4)
) (
    input  wire                    clock,
    input  wire                    rst,
    input  wire                    calc,
    output reg                     req,
    input  wire signed [IBITS-1:0] x_real,
    input  wire signed [IBITS-1:0] x_imag,
    output reg  signed [OBITS-1:0] y_real,
    output reg  signed [OBITS-1:0] y_imag
);

// Phase coefficient arrays PHASE0_COEF to PHASE3_COEF, 10 taps each.
`include "rtl/tx/fir_coeffs.vh"

    // Sample history, newest first: hist_*[0] is the most recently accepted input sample.
    reg signed [IBITS-1:0] hist_i [0:NP-1];
    reg signed [IBITS-1:0] hist_q [0:NP-1];
    reg [1:0] phase;

    // Product width: IBITS + COEFW, plus guard bits for summing NP taps.
    localparam PW    = IBITS + COEFW;
    localparam GUARD = 4;                 // ceil(log2(NP)) for NP<=16
    localparam ACCW  = PW + GUARD;
    // The coefficients are Q(COEFW-1), so their sum is about 2^(COEFW-1); the result is shifted back down to
    // OBITS bits, which carry (OBITS - IBITS) more guard and precision bits than the input.
    localparam SHIFT = (COEFW - 1) - (OBITS - IBITS);

    reg signed [ACCW-1:0] acc_i, acc_q;
    integer k;

    // On every calc, accumulate the 10 products of the current phase over the history, round, and output one
    // sample; after the 4th phase take in the next input sample.
    always @(posedge clock) begin
        if (rst) begin
            phase <= 2'd0;
            req   <= 1'b0;
            y_real <= {OBITS{1'b0}};
            y_imag <= {OBITS{1'b0}};
            for (k = 0; k < NP; k = k + 1) begin
                hist_i[k] <= {IBITS{1'b0}};
                hist_q[k] <= {IBITS{1'b0}};
            end
        end else if (calc) begin
            acc_i = {ACCW{1'b0}};
            acc_q = {ACCW{1'b0}};
            case (phase)
                2'd0: for (k = 0; k < NP; k = k + 1) begin
                    acc_i = acc_i + hist_i[k] * PHASE0_COEF[k];
                    acc_q = acc_q + hist_q[k] * PHASE0_COEF[k];
                end
                2'd1: for (k = 0; k < NP; k = k + 1) begin
                    acc_i = acc_i + hist_i[k] * PHASE1_COEF[k];
                    acc_q = acc_q + hist_q[k] * PHASE1_COEF[k];
                end
                2'd2: for (k = 0; k < NP; k = k + 1) begin
                    acc_i = acc_i + hist_i[k] * PHASE2_COEF[k];
                    acc_q = acc_q + hist_q[k] * PHASE2_COEF[k];
                end
                2'd3: for (k = 0; k < NP; k = k + 1) begin
                    acc_i = acc_i + hist_i[k] * PHASE3_COEF[k];
                    acc_q = acc_q + hist_q[k] * PHASE3_COEF[k];
                end
            endcase

            // Round to nearest: keep the top OBITS bits of the shifted accumulator and add the next lower bit
            // (the same truncate-and-bias convention as the HL2's own modules).
            y_real <= acc_i[SHIFT+OBITS-1 -: OBITS] + acc_i[SHIFT-1];
            y_imag <= acc_q[SHIFT+OBITS-1 -: OBITS] + acc_q[SHIFT-1];

            // After the last phase the history moves by one sample, the new input goes in and req asks for the
            // next one.
            if (phase == 2'd3) begin
                req <= 1'b1;
                for (k = NP-1; k > 0; k = k - 1) begin
                    hist_i[k] <= hist_i[k-1];
                    hist_q[k] <= hist_q[k-1];
                end
                hist_i[0] <= x_real;
                hist_q[0] <= x_imag;
                phase <= 2'd0;
            end else begin
                req   <= 1'b0;
                phase <= phase + 2'd1;
            end
        end else begin
            req <= 1'b0;
        end
    end

endmodule
