// Testbench for the receiver back end, rtl/rx_backend/rx_backend.v. The back end takes the shared stream of
// complex samples (an I and a Q value each, see docs/learn/GLOSSARY.md) that the receiver bank emits for
// up to 8 receivers and turns each receiver's stream into 12 or 24 ksps audio or IQ, through a decimator,
// a long complex channel filter, a CORDIC (which gives phase and magnitude), the demodulators, the AGC
// (automatic gain control), the S-meter and the squelch. All of that is fixed point arithmetic, and the
// reference for it is a bit-exact model written in Rust (fw/tr-dsp/src/backend), so this bench compares
// the hardware with the model word for word and does not use a tolerance anywhere.
//
// Stimulus: 8 receivers run at once. A stand-in for the receiver bank, written in this file, produces
// each receiver's samples every d_eff adc_valid pulses (d_eff is larger the lower that receiver's input
// rate) and puts them on the shared stream one per clock, round robin, while adc_valid itself comes in
// bursts that are high for about 51 % of the clocks (a harsher pattern than a steady stream, so the FIFOs and
// the engines see uneven arrival times). The samples of
// each receiver are the model's integer stimulus (two tones from a phase accumulator and the sine table
// sim/rx_backend/bk_sine.hex, xorshift32 noise, and impulses for the noise blanker), computed in
// stim_next exactly the way the Rust function tr_dsp::backend::stim computes them. The coefficient
// banks are generated the same way as the model's (pseudo-random, or a boxcar band-pass built from the
// sine table) and are written into the DUT through its register port, followed by the per-receiver
// settings.
//
// Scenario and expected results: the include sim/rx_backend/tb_rx_backend_scn.vh holds the register
// values, the stimulus parameters and, per receiver, what the model produced (number of output
// samples, a hash of every output word and stamp, final S-meter, AGC gain, squelch state and blanked
// count). That file is generated by `cargo run -p tr-dsp --example r4_check -- quick`, and a cargo test
// checks that it is current, so it is never edited by hand.
//
// Pass: every receiver's output count and hash equal the model's, the S-meter, squelch, AGC gain,
// blanked count and out_count registers read back as the model says, no overflow flag is set, the
// bank stand-in never overwrote a pending sample, and the ID register reads 0x5242_0001. The bench
// prints PASS, or FAIL lines naming the receiver and both values followed by "FAIL: n errors".
//
// How to run: from the repository root, `iverilog -g2012 -o tb.vvp sim/rx_backend/tb_rx_backend.v`
// and `vvp tb.vvp` (tools/check.sh does exactly this with the quick scenario). tools/run_r4_full.sh
// compiles it with -DFULL_SCN and the full scenarios instead (1,024 taps, real-time pacing, every
// mode at every rate, 8 receivers at 384 ksps, which takes a long time). The plusarg +dump=<prefix>
// writes every output as "s0 s1 stamp_offset" to <prefix>_rx<r>.txt for diffing against the model's
// expected files, and +trace=<rx> prints the internal values of one receiver while it runs.

`timescale 1ns / 1ps
`include "rtl/rx_backend/bk_mul.v"
`include "rtl/rx_backend/bk_ram.v"
`include "rtl/rx_backend/bk_rom.v"
`include "rtl/rx_backend/bk_fifo.v"
`include "rtl/rx_backend/bk_front.v"
`include "rtl/rx_backend/bk_decim.v"
`include "rtl/rx_backend/bk_chfilt.v"
`include "rtl/rx_backend/bk_cordic.v"
`include "rtl/rx_backend/bk_post.v"
`include "rtl/rx_backend/bk_ring.v"
`include "rtl/rx_backend/rx_backend.v"

// Number of receivers built: -DTB_NRX=<n> (default 8). With n <= 4 compile with -DTB_UNIT1_ABSENT as
// well, because there is then no second channel-filter unit to look into, and only receivers 0 to n-1
// of the scenario run.
`ifndef TB_NRX
`define TB_NRX 8
`endif

module tb_rx_backend;
    localparam integer NRX = `TB_NRX;
    // ------------------------------------------------------------ scenario arrays
    // One entry per coefficient bank (12 banks, 6 for each of the two channel-filter units): kind 0 is
    // pseudo-random coefficients, kind 1 a boxcar band-pass; ntaps and exp go into the bank
    // configuration register, seed and step shape the coefficients, shift scales them.
    integer bk_kind [0:11], bk_ntaps [0:11], bk_exp [0:11], bk_step [0:11], bk_shift [0:11];
    reg [31:0] bk_seed [0:11];
    // Per receiver (8): the register values the scenario writes (control word, noise blanker, AGC
    // attack, decay, hang, reference and gain limits, manual gain, loop settings, FM de-emphasis and
    // squelch thresholds).
    reg [31:0] cfg_ctrl [0:7], cfg_nb [0:7], cfg_hold [0:7], cfg_att [0:7], cfg_dec [0:7];
    reg [31:0] cfg_hang [0:7], cfg_ref [0:7], cfg_gmax [0:7], cfg_gmin [0:7], cfg_gman [0:7];
    reg [31:0] cfg_loops [0:7], cfg_deemph [0:7], cfg_sq [0:7];
    // Per receiver: the stimulus (amplitude and phase increment of the two tones, noise shift, noise
    // seed, impulse period and amplitude), how many samples to feed, the spacing in adc_valid pulses,
    // an optional coefficient bank switch (after swap_at filter outputs, to swap_bank), and the results
    // the model produced.
    integer st_amp0 [0:7], st_amp1 [0:7], st_nsh [0:7], st_imp_per [0:7], st_imp_amp [0:7];
    reg [31:0] st_inc0 [0:7], st_inc1 [0:7], st_seed [0:7];
    integer n_in [0:7], d_eff [0:7], swap_at [0:7], swap_bank [0:7];
    integer exp_count [0:7], exp_smeter [0:7], exp_gain [0:7], exp_sq [0:7], exp_blanked [0:7];
    reg [31:0] exp_hash [0:7];
`ifdef FULL_SCN
    `include "scn_full.vh"
`else
    `include "sim/rx_backend/tb_rx_backend_scn.vh"
`endif

    // ------------------------------------------------------------ clock, DUT
    reg clk = 1'b0;
    // Half period 3.333 ns makes a 6.666 ns period, which is the 150 MHz DSP clock of the chip.
    always #3.333 clk = ~clk;       // 150 MHz clk_dsp
    reg rst = 1'b1;

    // Shared input stream of the DUT: one sample of one receiver (in_index) per in_valid clock.
    reg         in_valid = 1'b0;
    reg  [2:0]  in_index = 3'd0;
    reg  [23:0] in_i = 24'd0, in_q = 24'd0;
    // Sample index of the HL2 ADC, which the DUT copies into each output's stamp; any start value will do.
    reg  [47:0] hl2_index = 48'h0000_1234_5678;
    // Plain synchronous register port, driven by the wr and rd tasks below.
    reg         reg_wr = 1'b0, reg_rd = 1'b0;
    reg  [15:0] reg_addr = 16'd0;
    reg  [31:0] reg_wdata = 32'd0;
    wire [31:0] reg_rdata;
    wire        out_valid, out_iq, irq;
    wire [2:0]  out_rx;
    wire [15:0] out_s0, out_s1;
    wire [47:0] out_stamp;

    // The ring_* write-lane port to DDR3 is left unconnected with no grant, because the output rings are
    // tested in tb_rx_backend_ring.v; this bench looks at out_valid and the registers only.
    rx_backend #(.NRX(NRX)) dut (
        .clk(clk), .rst(rst),
        .in_valid(in_valid), .in_index(in_index), .in_i(in_i), .in_q(in_q),
        .hl2_index(hl2_index),
        .reg_wr(reg_wr), .reg_rd(reg_rd), .reg_addr(reg_addr), .reg_wdata(reg_wdata), .reg_rdata(reg_rdata),
        .out_valid(out_valid), .out_rx(out_rx), .out_s0(out_s0), .out_s1(out_s1), .out_iq(out_iq),
        .out_stamp(out_stamp),
        .ring_req(), .ring_addr(), .ring_burstlen(), .ring_wdata(), .ring_wmask(),
        .ring_gnt(1'b0), .ring_done(1'b0), .irq(irq)
    );

    // ------------------------------------------------------------ helpers
    // One full period of a sine in 1,024 entries of 18 bits (signed, peak 2^17 - 1). A phase accumulator
    // uses its top 10 bits as the index, and the cosine is the same table a quarter period (256 entries)
    // ahead.
    reg [17:0] sine [0:1023];
    initial $readmemh("sim/rx_backend/bk_sine.hex", sine);

    // One step of the xorshift32 pseudo-random generator, the same one the model uses for noise and for
    // the random coefficients, so both sides see identical numbers.
    function [31:0] xs;             // xorshift32 step
        input [31:0] x;
        reg [31:0] v;
        begin
            v = x ^ (x << 13);
            v = v ^ (v >> 17);
            xs = v ^ (v << 5);
        end
    endfunction

    // Register write, one clock wide. swap_busy is set by the bank switch below while it is using the
    // bus, so that the two never write in the same clock (the DUT needs at least two clocks between
    // writes).
    reg swap_busy = 1'b0;
    task wr(input [15:0] a, input [31:0] d);
        begin
            @(posedge clk);
            while (swap_busy) @(posedge clk);
            reg_wr <= 1'b1; reg_addr <= a; reg_wdata <= d;
            @(posedge clk);
            reg_wr <= 1'b0;
        end
    endtask
    task rd(input [15:0] a, output [31:0] d);
        begin
            @(posedge clk);
            reg_rd <= 1'b1; reg_addr <= a;
            @(posedge clk);
            reg_rd <= 1'b0;
            @(posedge clk);
            // Five extra clocks of waiting: the DUT registers the bus once, latches the read address,
            // and its read multiplexer takes two clocks per step (first by receiver, then by field) as
            // two-clock paths (see "register bus" in rx_backend.v), so read data is valid six clocks
            // after reg_rd, not one.
            repeat (3) @(posedge clk);
            @(posedge clk);
            @(posedge clk);
            d = reg_rdata;
        end
    endtask

    // ------------------------------------------------------------ stimulus (tr_dsp::backend::stim)
    // One new sample for receiver r in gi (I) and gq (Q), 24-bit signed. Each of the two tones is a
    // complex exponential: amp * sine / 2^17 gives a peak of amp, and the phase accumulator advances by
    // its increment per sample, so the tone frequency is inc / 2^32 times the receiver's sample rate.
    // Noise is a new random number for I and one for Q shifted right by nsh (the larger nsh, the
    // quieter). Every impulse period two samples are replaced by an impulse (I = imp_amp, Q =
    // -imp_amp / 2) to exercise the noise blanker. The result is clipped to the 24-bit range.
    reg [31:0] ph0 [0:7], ph1 [0:7], rng [0:7];
    integer    sn  [0:7];
    reg signed [63:0] gi, gq;
    task stim_next(input integer r);
        reg [9:0] idx;
        begin
            gi = 64'sd0; gq = 64'sd0;
            if (st_amp0[r] != 0) begin
                idx = ph0[r][31:22];
                gi = gi + (($signed(st_amp0[r]) * $signed(sine[(idx + 10'd256) & 10'd1023])) >>> 17);
                gq = gq + (($signed(st_amp0[r]) * $signed(sine[idx])) >>> 17);
            end
            ph0[r] = ph0[r] + st_inc0[r];
            if (st_amp1[r] != 0) begin
                idx = ph1[r][31:22];
                gi = gi + (($signed(st_amp1[r]) * $signed(sine[(idx + 10'd256) & 10'd1023])) >>> 17);
                gq = gq + (($signed(st_amp1[r]) * $signed(sine[idx])) >>> 17);
            end
            ph1[r] = ph1[r] + st_inc1[r];
            if (st_nsh[r] > 0) begin
                rng[r] = xs(rng[r]);
                gi = gi + ($signed(rng[r]) >>> st_nsh[r]);
                rng[r] = xs(rng[r]);
                gq = gq + ($signed(rng[r]) >>> st_nsh[r]);
            end
            if (st_imp_per[r] > 0 && (sn[r] % st_imp_per[r]) < 2) begin
                gi = st_imp_amp[r];
                gq = -($signed(st_imp_amp[r]) >>> 1);
            end
            sn[r] = sn[r] + 1;
            if (gi > 64'sd8388607) gi = 64'sd8388607;
            if (gi < -64'sd8388608) gi = -64'sd8388608;
            if (gq > 64'sd8388607) gq = 64'sd8388607;
            if (gq < -64'sd8388608) gq = -64'sd8388608;
        end
    endtask

    // ------------------------------------------------------------ adc_valid, bank stand-in
    // Each receiver has a counter cnt that counts adc_valid pulses; when it reaches d_eff the receiver
    // gets a new sample (pend, pi, pq). If the previous one was still waiting it is overwritten and
    // counted in lost, which the final check requires to stay 0.
    reg        running = 1'b0;
    reg        adc_valid = 1'b0;
    reg [31:0] vrng = 32'h9E37_79B9;
    integer    vleft = 0;
    integer    cnt [0:7];
    reg        pend [0:7];
    reg [23:0] pi [0:7], pq [0:7];
    integer    rr = 0;
    integer    lost = 0;
    integer    k, m, pick;
    integer    n_valid = 0, n_cycles = 0;

    always @(posedge clk) begin
        if (running) begin
            // Bursty adc_valid: runs of 1 to 48 valid clocks and gaps of 1 to 46, which averages
            // 24.5 against 23.5 clocks, so about 51 % of the clocks are valid.
            if (vleft == 0) begin
                vrng = xs(vrng);
                adc_valid = !adc_valid;
                vleft = adc_valid ? 1 + (vrng % 48) : 1 + (vrng % 46);
            end
            vleft = vleft - 1;
            n_cycles = n_cycles + 1;
            if (adc_valid) begin
                n_valid = n_valid + 1;
                hl2_index <= hl2_index + 48'd1;
                for (k = 0; k < NRX; k = k + 1) begin
                    if (sn[k] < n_in[k]) begin
                        cnt[k] = cnt[k] + 1;
                        if (cnt[k] >= d_eff[k]) begin
                            cnt[k] = 0;
                            if (pend[k]) lost = lost + 1;
                            stim_next(k);
                            pend[k] = 1'b1;
                            pi[k] = gi[23:0];
                            pq[k] = gq[23:0];
                        end
                    end
                end
            end
            // Shared stream: one pending receiver per clock, picked round robin starting after the
            // receiver sent last.
            in_valid <= 1'b0;
            pick = -1;
            for (m = 0; m < NRX; m = m + 1)
                if (pick < 0 && pend[(rr + m) % NRX]) pick = (rr + m) % NRX;
            if (pick >= 0) begin
                in_valid <= 1'b1;
                in_index <= pick[2:0];
                in_i <= pi[pick];
                in_q <= pq[pick];
                pend[pick] = 1'b0;
                rr = (pick + 1) % NRX;
            end
        end
    end

    // ------------------------------------------------------------ bank switch at a 24 ksps sample
    // cf_done counts the samples each receiver has pushed out of the two channel-filter units (the
    // receiver number sits in bits 51:49 of the pushed word). When a receiver with swap_at >= 0 reaches
    // that count its control register is written again with another coefficient bank selected, which
    // is the same moment the model switches banks, so the output stays identical.
    integer cf_done [0:7];
    always @(posedge clk) begin
        if (dut.unit[0].u_cf.out_push) cf_done[dut.unit[0].u_cf.out_data[51:49]] = cf_done[dut.unit[0].u_cf.out_data[51:49]] + 1;
`ifndef TB_UNIT1_ABSENT
        if (dut.unit[1].u_cf.out_push) cf_done[dut.unit[1].u_cf.out_data[51:49]] = cf_done[dut.unit[1].u_cf.out_data[51:49]] + 1;
`endif
    end
    integer sw;
    reg [7:0] swapped = 8'd0;
    always @(posedge clk) begin
        for (sw = 0; sw < NRX; sw = sw + 1)
            if (running && !swapped[sw] && swap_at[sw] >= 0 && cf_done[sw] == swap_at[sw]) begin
                swapped[sw] = 1'b1;
                swap_busy = 1'b1;
                reg_wr <= 1'b1;
                reg_addr <= `RX_BACKEND_CTRL_ADDR(sw);
                reg_wdata <= (cfg_ctrl[sw] & ~(32'h7 << `RX_BACKEND_CTRL_BANK_SEL_LSB)) |
                             (swap_bank[sw] << `RX_BACKEND_CTRL_BANK_SEL_LSB) | 32'd1;
                @(posedge clk);
                reg_wr <= 1'b0;
                swap_busy = 1'b0;
            end
    end

    // ------------------------------------------------------------ +trace=<rx>: channel-filter outputs
    // Debug aid only, with no effect on pass or fail: with +trace=<rx> the values of one receiver are
    // printed at the decimator output (D), the channel filter outputs (Y) and inside the post engine (P).
    integer trace_rx = -1;
    initial if (!$value$plusargs("trace=%d", trace_rx)) trace_rx = -1;
    always @(posedge clk) begin
        if (dut.d_push && dut.d_data[51:49] == trace_rx)
            $display("D %0d %0d", $signed(dut.d_data[47:24]), $signed(dut.d_data[23:0]));
        if (dut.u_post.st == 17 && dut.u_post.rx == trace_rx)
            $display("P y %0d %0d M %0d L %0d g %0d ga %0d a %0d %0d -> %0d %0d fill %0d phs %0d th %0d fr %0d dc %0d", dut.u_post.yr, dut.u_post.yi,
                     dut.u_post.mag, dut.u_post.lvl, dut.u_post.w_g, dut.u_post.ga, dut.u_post.aa, dut.u_post.ab,
                     dut.u_post.ga_i, dut.u_post.ga_q, dut.u_post.w_fill, dut.u_post.w_phs, dut.u_post.w_th, dut.u_post.w_fr, dut.u_post.w_dc);
        if (dut.u_post.st == 20 && dut.u_post.rx == trace_rx)
            $display("MEND acc %0d q %0d", dut.u_post.acc, dut.u_post.mac_q);
        if (dut.unit[0].u_cf.out_push && dut.unit[0].u_cf.out_data[51:49] == trace_rx)
            $display("Y %0d %0d", $signed(dut.unit[0].u_cf.out_data[47:24]), $signed(dut.unit[0].u_cf.out_data[23:0]));
`ifndef TB_UNIT1_ABSENT
        if (dut.unit[1].u_cf.out_push && dut.unit[1].u_cf.out_data[51:49] == trace_rx)
            $display("Y %0d %0d", $signed(dut.unit[1].u_cf.out_data[47:24]), $signed(dut.unit[1].u_cf.out_data[23:0]));
`endif
    end

    // ------------------------------------------------------------ engine load (reported at the end)
    // Counts the clocks each engine (decimator, the two filter units, the post engine) is not idle and
    // the peak fill of the first input FIFO, as a margin report that is printed at the end.
    integer busy_dec = 0, busy_cf0 = 0, busy_cf1 = 0, busy_post = 0, fill_a_max = 0, fill_a;
    always @(posedge clk) if (running) begin
        if (dut.u_decim.st != 0) busy_dec = busy_dec + 1;
        if (dut.unit[0].u_cf.st != 0) busy_cf0 = busy_cf0 + 1;
`ifndef TB_UNIT1_ABSENT
        if (dut.unit[1].u_cf.st != 0) busy_cf1 = busy_cf1 + 1;
`endif
        if (dut.u_post.st != 0) busy_post = busy_post + 1;
        fill_a = dut.u_fa.wp - dut.u_fa.rp;
        if (fill_a < 0) fill_a = fill_a + 128;
        if (fill_a > fill_a_max) fill_a_max = fill_a;
    end

    // ------------------------------------------------------------ output check
    // Every output word goes into a per-receiver hash: FNV-1a style, start value 0x811C9DC5 and prime
    // 0x01000193, applied first to the 32 bits {s1, s0} and then to the stamp offset (the output stamp
    // minus the stamp stored for that receiver, which is the HL2 sample index when its first input
    // sample came in). The model computes the same hash over its own outputs.
    reg [31:0] hash [0:7];
    integer    cnt_out [0:7];
    integer    fd [0:7];
    reg        dumping = 1'b0;
    string     dump_prefix;
    reg [47:0] soff;
    always @(posedge clk) begin
        if (out_valid) begin
            soff = out_stamp - dut.m_stamp.mem[out_rx];
            hash[out_rx] = (hash[out_rx] ^ {out_s1, out_s0}) * 32'h0100_0193;
            hash[out_rx] = (hash[out_rx] ^ soff[31:0]) * 32'h0100_0193;
            cnt_out[out_rx] = cnt_out[out_rx] + 1;
            if (dumping)
                $fwrite(fd[out_rx], "%0d %0d %0d\n", $signed(out_s0), $signed(out_s1), soff);
        end
    end

    // ------------------------------------------------------------ main
    integer r, n, errors, done_all, t0, ntot;
    reg [31:0] v, ci, cq, crng;
    reg [9:0]  cidx;
    initial begin
        errors = 0;
        scn_load;
        for (r = 0; r < NRX; r = r + 1) begin
            ph0[r] = 0; ph1[r] = 0; rng[r] = st_seed[r] | 1; sn[r] = 0;
            // Starting values of the counters are staggered from 0 down to -6 so that the receivers do
            // not all become due on the same adc_valid pulse.
            cnt[r] = -(r * 13) % 7; pend[r] = 1'b0; hash[r] = 32'h811C_9DC5; cnt_out[r] = 0;
            cf_done[r] = 0;
        end
        if ($value$plusargs("dump=%s", dump_prefix)) begin
            dumping = 1'b1;
            for (r = 0; r < NRX; r = r + 1)
                fd[r] = $fopen($sformatf("%0s_rx%0d.txt", dump_prefix, r), "w");
        end
        repeat (5) @(posedge clk);
        rst = 1'b0;
        repeat (5) @(posedge clk);

        // Coefficient banks: select unit n / 6 and bank n % 6, write ntaps and exp, then the complex
        // coefficients, I at COEF_OFFSET + 8 m and Q four bytes above. Kind 0 uses random values from
        // xorshift32 shifted down by bk_shift, kind 1 uses the sine table at index m * step, so the
        // taps form a complex tone, which makes a band-pass filter when they are a boxcar window.
        // coefficient banks
        for (n = 0; n < 12; n = n + 1) begin
            wr(`RX_BACKEND_COEF_SEL_ADDR, ((n % 6) << 1) | (n / 6));
            wr(`RX_BACKEND_BANK_CFG_ADDR(n), bk_ntaps[n] | (bk_exp[n] << 12));
            crng = bk_seed[n] | 1;
            for (m = 0; m < bk_ntaps[n]; m = m + 1) begin
                if (bk_kind[n] == 0) begin
                    crng = xs(crng); ci = $signed(crng) >>> bk_shift[n];
                    crng = xs(crng); cq = $signed(crng) >>> bk_shift[n];
                end else begin
                    cidx = (m * bk_step[n]) & 1023;
                    ci = $signed(sine[(cidx + 10'd256) & 10'd1023]) <<< bk_shift[n];
                    cq = $signed(sine[cidx]) <<< bk_shift[n];
                end
                wr(`RX_BACKEND_COEF_OFFSET + 8 * m, ci);
                wr(`RX_BACKEND_COEF_OFFSET + 8 * m + 4, cq);
            end
        end
        // Receivers: all settings first with the enable bit (bit 0 of the control word) clear, then
        // one more write of the control word with it set.
        // receivers
        for (r = 0; r < NRX; r = r + 1) begin
            wr(`RX_BACKEND_NB_ADDR(r), cfg_nb[r]);
            wr(`RX_BACKEND_NB_HOLD_ADDR(r), cfg_hold[r]);
            wr(`RX_BACKEND_AGC_ATTACK_ADDR(r), cfg_att[r]);
            wr(`RX_BACKEND_AGC_DECAY_ADDR(r), cfg_dec[r]);
            wr(`RX_BACKEND_AGC_HANG_ADDR(r), cfg_hang[r]);
            wr(`RX_BACKEND_AGC_REF_ADDR(r), cfg_ref[r]);
            wr(`RX_BACKEND_AGC_GMAX_ADDR(r), cfg_gmax[r]);
            wr(`RX_BACKEND_AGC_GMIN_ADDR(r), cfg_gmin[r]);
            wr(`RX_BACKEND_AGC_MANUAL_ADDR(r), cfg_gman[r]);
            wr(`RX_BACKEND_LOOPS_ADDR(r), cfg_loops[r]);
            wr(`RX_BACKEND_FM_DEEMPH_ADDR(r), cfg_deemph[r]);
            wr(`RX_BACKEND_SQUELCH_ADDR(r), cfg_sq[r]);
            wr(`RX_BACKEND_CTRL_ADDR(r), cfg_ctrl[r]);
        end
        for (r = 0; r < NRX; r = r + 1)
            wr(`RX_BACKEND_CTRL_ADDR(r), cfg_ctrl[r] | 32'd1);
        running = 1'b1;
        t0 = $time;

        // Run until every receiver has had all its input and produced all its output, or give up after
        // 0.4 s of simulated time (400,000,000 ns, about 60 million clocks).
        // run until every receiver has had all its input and produced all its output
        done_all = 0;
        while (!done_all) begin
            repeat (1000) @(posedge clk);
            done_all = 1;
            for (r = 0; r < NRX; r = r + 1)
                if (sn[r] < n_in[r] || cnt_out[r] < exp_count[r]) done_all = 0;
            if (($time - t0) > 400_000_000) begin
                $display("FAIL: timeout");
                for (r = 0; r < NRX; r = r + 1)
                    $display("  rx%0d: fed %0d of %0d, %0d of %0d outputs", r, sn[r], n_in[r], cnt_out[r], exp_count[r]);
                $finish;
            end
        end
        // Let the last inputs run through every stage.
        repeat (40000) @(posedge clk);     // let the last inputs through every stage

        // Compare with the model: output count and hash first, then the registers (S-meter in bits
        // 15:0 of the status word and the squelch state in bit 16, AGC gain, blanked count, out_count).
        // compare
        ntot = 0;
        for (r = 0; r < NRX; r = r + 1) begin
            ntot = ntot + cnt_out[r];
            if (cnt_out[r] != exp_count[r] || hash[r] !== exp_hash[r]) begin
                $display("FAIL rx%0d: %0d outputs, hash %08x; model %0d outputs, hash %08x", r, cnt_out[r], hash[r], exp_count[r], exp_hash[r]);
                errors = errors + 1;
            end
            rd(`RX_BACKEND_RX_STATUS_ADDR(r), v);
            if ($signed(v[15:0]) != exp_smeter[r] || v[16] != exp_sq[r]) begin
                $display("FAIL rx%0d: S-meter %0d squelch %0d; model %0d %0d", r, $signed(v[15:0]), v[16], exp_smeter[r], exp_sq[r]);
                errors = errors + 1;
            end
            rd(`RX_BACKEND_AGC_GAIN_ADDR(r), v);
            if ($signed(v) != exp_gain[r]) begin
                $display("FAIL rx%0d: AGC gain %0d; model %0d", r, $signed(v), exp_gain[r]);
                errors = errors + 1;
            end
            rd(`RX_BACKEND_BLANKED_ADDR(r), v);
            if (v != exp_blanked[r]) begin
                $display("FAIL rx%0d: blanked %0d; model %0d", r, v, exp_blanked[r]);
                errors = errors + 1;
            end
            rd(`RX_BACKEND_OUT_COUNT_ADDR(r), v);
            if (v != exp_count[r]) begin
                $display("FAIL rx%0d: out_count register %0d; model %0d", r, v, exp_count[r]);
                errors = errors + 1;
            end
        end
        // Overflow flags of the FIFOs inside the DUT must all be clear, and the bank stand-in must not
        // have lost a sample.
        rd(`RX_BACKEND_STATUS_ADDR, v);
        if (v != 0 || lost != 0) begin
            $display("FAIL: overflow flags %b, bank stand-in lost %0d samples", v[3:0], lost);
            errors = errors + 1;
        end
        // The ID register reads 'R' 'B' (0x52 0x42) and the layout version 1.
        rd(`RX_BACKEND_ID_ADDR, v);
        if (v != 32'h5242_0001) begin
            $display("FAIL: id %08x", v);
            errors = errors + 1;
        end
        if (dumping)
            for (r = 0; r < NRX; r = r + 1) $fclose(fd[r]);
        $display("rx_backend: %0d outputs from %0d receivers compared with the model, adc_valid %0d %% of %0d cycles",
                 ntot, NRX, (100 * n_valid) / n_cycles, n_cycles);
        $display("engine busy: decimator %0d %%, filter units %0d %% / %0d %%, post %0d %%; input FIFO peak %0d of 64",
                 (100 * busy_dec) / n_cycles, (100 * busy_cf0) / n_cycles, (100 * busy_cf1) / n_cycles,
                 (100 * busy_post) / n_cycles, fill_a_max);
        if (errors == 0)
            $display("PASS");
        else
            $display("FAIL: %0d errors", errors);
        $finish;
    end
