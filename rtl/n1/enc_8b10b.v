// 8b/10b encoder: one byte in, one 10-bit code group out, per clock. See sfp_enc20.v for what 8b/10b is
// and why the coder keeps a running disparity. The PCS (sfp_pcs.v) sends its symbols through this module on
// the 10-bit lane (sfp_phy.v), and the two-symbols-per-clock encoder for the 20-bit lane is sfp_enc20.v.
// It works at the level of code groups, after the byte has become a symbol and before the serializer
// puts it on the line.
//
// The table is in rtl/n1/tab_8b10b.vh (generated by rtl/n1/gen_8b10b_table.py from the public IEEE 802.3
// clause 36 tables). `din` and `kin` use the same {y[2:0], x[4:0]} packing as the table: for a data byte it
// is just the byte value, and for a control (K) request only the 12 legal (x, y) pairs are valid
// (rtl/n1/n1_codes.vh gives names for the ones used).
//
// How it works: a table entry is 11 bits, the 10-bit code group and, in bit 0, the running disparity after
// the symbol. The register `rd` holds the disparity before the next symbol (0 means negative, 1 means
// positive) and selects the entry. The output `rd_out` shows the disparity now in effect, for the caller's
// choice between the two idle sets /I1/ and /I2/ (IEEE 802.3 36.2.4.13).
//
// Latency: 1 clock.

`timescale 1ns / 1ps

module enc_8b10b (
    input  wire       clk,        // lane word clock
    input  wire       rst,        // synchronous reset, running disparity to negative

    input  wire [7:0] din,     // byte to encode this cycle
    input  wire       kin,     // 1: din is one of the 12 legal K control codes

    output reg  [9:0] dout,    // registered 10-bit code group for the din/kin sampled last cycle
    output reg        rd_out,  // running disparity now in effect (0 => -1, 1 => +1), for the
                                // caller's idle I1/I2 selection (36.2.4.13)
    output reg        valid    // 0 for the first cycle after rst
);

`include "tab_8b10b.vh"

    reg rd = 1'b0;

    wire [10:0] sel = kin ? enc8b10b_k(din, rd) : enc8b10b_d(din, rd);

    always @(posedge clk) begin
        if (rst) begin
            rd     <= 1'b0;
            dout   <= 10'b0;
            rd_out <= 1'b0;
            valid  <= 1'b0;
        end else begin
            dout   <= sel[10:1];
            rd     <= sel[0];
            rd_out <= sel[0];
            valid  <= 1'b1;
        end
    end

endmodule
