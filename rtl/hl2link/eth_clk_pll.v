// Clock generator for the RJ45 network unit: turns the board's 50 MHz oscillator into the 100 MHz
// clock that rtl/net/net_unit.v (the network unit behind the RJ45 socket) runs on, and into a
// 25 MHz clock that is generated but not used.
//
// Where it sits: the 50 MHz oscillator (FPGA pin P16 on the Tang Mega 138K Pro) feeds it, and
// `clk_100` (called clk_eth in the rest of the design) feeds the network unit, whose logic
// divides it by four to make the 25 MHz transmit clock and the PHY reference clock of its
// 100 Mbit/s Ethernet interface (docs/HL2_SFP.md section 9). The Hermes-Lite 2 link itself no
// longer uses the RJ45 PHY, since it now arrives over the SFP lane, so no 125 MHz RGMII clock is
// needed any more.
//
// How the PLL works, for a beginner: a PLL (phase-locked loop) multiplies a reference clock up to
// a much faster internal one, the VCO (voltage controlled oscillator), and then divides that down
// again into one or more output clocks. Here the reference is 50 MHz and the VCO runs at
// 1,000 MHz (50 MHz x 20, which is within the 650 to 1,300 MHz range the VCO of the GW5AST-138
// allows, UG306 section 5.1). The output frequency is Fvco divided by the output divider, so
// output 0 (divider 10) gives 100 MHz and output 1 (divider 40) gives 25 MHz. `locked` goes high
// when the loop has settled, and the clocks must not be trusted before that.
//
// Gowin specific point: on the GW5A family the PLL is the PLL_ADV primitive, which the build
// generates as the module Gowin_PLL_ETH from gowin/p1/ip/gowin_pll_eth.mod. The module is only
// instantiated when GOWIN_PLL is defined. Without that define, a simulation gets free-running
// behavioural clocks instead.

`timescale 1ns / 1ps

module eth_clk_pll (
    input  wire clk_in,     // 50 MHz board oscillator
    output wire clk_100,    // the network unit's clock, 100 MHz (VCO divided by 10)
    output wire clk_25,     // 25 MHz (VCO divided by 40), generated but not used
    output wire locked      // high when the PLL has locked onto the reference
);

`ifdef GOWIN_PLL

    // The Gowin PLL, generated by the build from the .mod file named in the header. The enclk
    // inputs enable the two output clocks and are tied high, and the reset is not used.
    Gowin_PLL_ETH u_pll (
        .clkin(clk_in), .reset(1'b0), .lock(locked),
        .clkout0(clk_100), .clkout1(clk_25),
        .enclk0(1'b1), .enclk1(1'b1)
    );

`else

    // Behavioural clocks for simulation: free-running at the target frequencies, with `locked`
    // rising after a fixed settle time (which stands in for the PLL's own lock time; the exact
    // figure does not matter to any testbench behind this module, since they all wait for
    // `locked` and not for a fixed delay).
    reg clk_100_r = 1'b0;
    reg clk_25_r  = 1'b0;
    reg locked_r  = 1'b0;

    always #5.000  clk_100_r = ~clk_100_r;   // 100 MHz
    always #20.000 clk_25_r  = ~clk_25_r;    // 25 MHz

    initial begin
        locked_r = 1'b0;
        #1000;             // arbitrary settle, well past any real PLL's lock time
        locked_r = 1'b1;
    end

    assign clk_100 = clk_100_r;
    assign clk_25  = clk_25_r;
    assign locked  = locked_r;

`endif

endmodule
