// The chip's transceiver for the two SFP+ cages (docs/SFP_LINKS.md section 2): a wrapper around
// Gowin's Customized PHY block for quad 1 of the GW5AST-138, with lane 0 (cage SFP0, which carries the
// Hermes-Lite 2 link at 1.25 Gbit/s, 10-bit words) and lane 1 (cage SFP1, the board-to-board link at
// 2.5 Gbit/s, 20-bit words). Both lanes run raw, with no 8b/10b and no alignment in the hard block
// (those are done in logic, see sfp_rx_sym.v and sfp_enc20.v), from reference input 1 at 125 MHz.
//
// What a transceiver is, for a beginner: a SerDes (serializer and deserializer) turns the 10 or 20 bits
// of a word on the FPGA side into a serial bit stream at 1.25 or 2.5 Gbit/s on a differential pair, and
// back. The receive half recovers a clock from the incoming bit transitions (CDR, clock and data
// recovery), which is why the receive clock `n1_rxc` is not the same as the transmit clock. A lane has a
// PLL that makes the line-rate clock from the 125 MHz reference, which has to lock first.
// The user side of each lane is a FIFO each way: a transmit buffer written with `tx_clk_i` and a receive
// buffer read with `rx_clk_i`, and a word is marked by `rx_valid`.
//
// Vendor block: `Serdes_Top` is generated by gowin/p1/build.sh with GowinModGen from
// gowin/p1/ip/serdes/serdes.ipc, and the lane settings are the register file made from
// gowin/p1/ip/serdes/serdes.toml. It is not simulated; the testbenches use sim/sfp/sfp_lane_model.v in its
// place.
//
// Reset form (docs/SFP_LINKS.md 2.3): by default the IDE's (the build defines `TR_SFP_NO_POR`, so there is
// no `por_n_i`; the quad starts at configuration, and the firmware restarts each lane with `pma_rstn_i`
// once the reference runs). With SFP_POR_FABRIC=1 the build makes Gowin's "Global Reset Enable" form
// (IPUG1024-1.7.2E 3.2) and `por_n` drives `por_n_i`. On this board the lane PLL locks in the IDE's form.
//
// IPUG1024-1.7.2E: 3.7 (the user side is a FIFO each way: `tx_clk_i` is the write clock of the transmit
// buffer, `rx_clk_i` the read clock of the receive buffer; write while not almost full, read while not
// almost empty, `rx_valid` marks a word), tables 3-5 and 3-8 (without 8b/10b a 10-bit word is bits 9:0, a
// 20-bit word bits 19:0, low bit first on the line), 3.2 (`por_n_i`), table 4-1 (ports).
//
// `bl_txc` is the clock that lane 1's transmit buffer is written with. The chip top gives it `sfp_txc`,
// lane 0's transmit clock: both transmit clocks are 125 MHz made from the same reference, so the buffer
// neither fills nor empties, and that saves a clock line. With TR_SFP_TXC_OWN it gives `ln1_txc` (a
// fourth clock).
//
// Words on the fabric side are in line order (bit 0 first). `ln*_fix` are register bits for bring-up on
// a board: bit 0 reverses the transmit bit order within each 10-bit symbol, 1 the receive order, 2 inverts
// the transmit bits, 3 the receive bits.
//
// `diag`: 7:0 the quad's own status, a port that the build adds to the generated wrapper (0 CMU0 OK, 1
// CMU1 OK, 2 reference detect CM0, 3 reference detect CM1, 4 lane 0 CMU OK, 5 lane 1 CMU OK, 6 lane 0 PMA
// receive lock, 7 lane 1 PMA receive lock); 11:8 sticky flags since the lane's PCS reset was last released:
// 8 lane 0 transmit buffer was almost full (a word was not written), 9 lane 0 receive buffer was almost
// empty (a clock without a word), 10 and 11 the same for lane 1. They are asynchronous levels.

`timescale 1ns / 1ps

module sfp_serdes (
    input  wire        por_n,            // power-on reset of the quad, active low (used only with the global reset form)
    input  wire [1:0]  ln_rst_n,         // lane resets, active low: the whole lane, its PLL included
    input  wire [1:0]  ln_rx_rst,        // PCS receive resets, active high
    input  wire [1:0]  ln_tx_rst,        // PCS transmit resets, active high
    input  wire [3:0]  ln0_fix,          // lane 0 bring-up bits (see header)
    input  wire [3:0]  ln1_fix,          // lane 1 bring-up bits
    output wire        sfp_txc,          // lane 0 transmit word clock, 125 MHz
    output wire        n1_rxc,           // lane 0 recovered receive word clock, 125 MHz
    input  wire        bl_txc,           // the clock lane 1's transmit buffer is written with: sfp_txc, or ln1_txc
    output wire        ln1_txc,          // lane 1's own transmit clock (unused when sfp_txc is shared)
    output wire        bl_rxc,           // lane 1 recovered receive word clock, 125 MHz
    input  wire [9:0]  ln0_tx,           // lane 0 word to send (in sfp_txc)
    output reg  [9:0]  ln0_rx = 10'd0,   // lane 0 word received (in n1_rxc)
    output reg         ln0_rx_vld = 1'b0, // ln0_rx holds a new word
    input  wire [19:0] ln1_tx,           // lane 1 word to send (in bl_txc)
    output reg  [19:0] ln1_rx = 20'd0,   // lane 1 word received (in bl_rxc)
    output reg         ln1_rx_vld = 1'b0, // ln1_rx holds a new word
    output wire [3:0]  ln0_stat,         // 0 PLL lock, 1 receive clock lock, 2 signal detect, 3 ready
    output wire [3:0]  ln1_stat,
    output wire [11:0] diag              // quad status and buffer flags (see header)
);

    // Bit reversal and inversion of a 10-bit symbol, for bring-up if the line order or polarity on
    // a board turns out to be the other way round.
    function [9:0] fix10(input [9:0] w, input rev, input inv);
        reg [9:0] r;
        begin
            r = rev ? {w[0], w[1], w[2], w[3], w[4], w[5], w[6], w[7], w[8], w[9]} : w;
            fix10 = inv ? ~r : r;
        end
    endfunction

    wire        txc0, txc1, rxc0, rxc1;
    wire [87:0] rxd0, rxd1;
    wire        rxv0, rxv1, rxae0, rxae1, txaf0, txaf1;
    reg  [9:0]  t0 = 10'd0;
    reg  [19:0] t1 = 20'd0;
    wire [7:0]  qd;
    // A register in each FIFO enable (wr_en0, wr_en1, rd_en0, rd_en1), because an inverter between the
    // block's almost-full or almost-empty flag and its enable can be placed far away and cost several
    // nanoseconds each way. With equal read and write clocks the flags are constant (IPUG1024-1.7.2E
    // 3.7.1, 3.7.2), so one clock of delay changes nothing; when they are not, almost full and almost empty
    // leave room for the one more word written or read.
    reg         wr_en0 = 1'b0, wr_en1 = 1'b0, rd_en0 = 1'b0, rd_en1 = 1'b0;
    // Sticky gap flags (`diag` bits 11:8), cleared while the lane's PCS side is in reset (that reset
    // synchronized into the lane clock by `tr0`, `tr1`, `rr0` and `rr1`): a transmit word that was not
    // written, or a receive clock without a word.
    reg  [1:0]  tr0 = 2'b11, tr1 = 2'b11, rr0 = 2'b11, rr1 = 2'b11;
    reg         tx_gap0 = 1'b0, tx_gap1 = 1'b0, rx_gap0 = 1'b0, rx_gap1 = 1'b0;
    assign diag = {rx_gap1, tx_gap1, rx_gap0, tx_gap0, qd};

    assign sfp_txc = txc0;
    assign n1_rxc  = rxc0;
    assign bl_rxc  = rxc1;
    assign ln1_txc = txc1;

    // Lane 0 transmit side: the word goes through the bring-up fix into a register `t0`, and the
    // write enable is "not almost full".
    always @(posedge sfp_txc) begin
        t0      <= fix10(ln0_tx, ln0_fix[0], ln0_fix[2]);
        wr_en0  <= ~txaf0;
        tr0     <= {tr0[0], ln_tx_rst[0]};
        tx_gap0 <= tr0[1] ? 1'b0 : tx_gap0 | ~wr_en0;
    end
    always @(posedge bl_txc) begin
        t1      <= {fix10(ln1_tx[19:10], ln1_fix[0], ln1_fix[2]), fix10(ln1_tx[9:0], ln1_fix[0], ln1_fix[2])};
        wr_en1  <= ~txaf1;
        tr1     <= {tr1[0], ln_tx_rst[1]};
        tx_gap1 <= tr1[1] ? 1'b0 : tx_gap1 | ~wr_en1;
    end
    // Lane 0 receive side: the word and its valid flag are registered, and the read enable is
    // "not almost empty" (a clock with the enable low carries no word, which `rx_valid` marks).
    always @(posedge n1_rxc) begin
        ln0_rx     <= fix10(rxd0[9:0], ln0_fix[1], ln0_fix[3]);
        ln0_rx_vld <= rxv0;
        rd_en0     <= ~rxae0;
        rr0        <= {rr0[0], ln_rx_rst[0]};
        rx_gap0    <= rr0[1] ? 1'b0 : rx_gap0 | ~rd_en0;
    end
    always @(posedge bl_rxc) begin
        ln1_rx     <= {fix10(rxd1[19:10], ln1_fix[1], ln1_fix[3]), fix10(rxd1[9:0], ln1_fix[1], ln1_fix[3])};
        ln1_rx_vld <= rxv1;
        rd_en1     <= ~rxae1;
        rr1        <= {rr1[0], ln_rx_rst[1]};
        rx_gap1    <= rr1[1] ? 1'b0 : rx_gap1 | ~rd_en1;
    end

    // Lane lines are named by Gowin's generated wrapper: lane 0 is `ln0` and lane 1 `ln1` of quad 1.
    // The data ports are 88 bits wide on the receive side and 80 on the transmit side, of which only the low
    // 10 or 20 are used.
    Serdes_Top u_serdes (
`ifndef TR_SFP_NO_POR
        .por_n_i(por_n),
`endif
        .sfp_diag(qd),
        // lane 0
        .Customized_PHY_Top_q1_ln0_rx_pcs_clkout_o(rxc0), .Customized_PHY_Top_q1_ln0_rx_data_o(rxd0),
        .Customized_PHY_Top_q1_ln0_rx_fifo_rdusewd_o(), .Customized_PHY_Top_q1_ln0_rx_fifo_aempty_o(rxae0),
        .Customized_PHY_Top_q1_ln0_rx_fifo_empty_o(), .Customized_PHY_Top_q1_ln0_rx_valid_o(rxv0),
        .Customized_PHY_Top_q1_ln0_tx_pcs_clkout_o(txc0), .Customized_PHY_Top_q1_ln0_tx_fifo_wrusewd_o(),
        .Customized_PHY_Top_q1_ln0_tx_fifo_afull_o(txaf0), .Customized_PHY_Top_q1_ln0_tx_fifo_full_o(),
        .Customized_PHY_Top_q1_ln0_refclk_o(), .Customized_PHY_Top_q1_ln0_signal_detect_o(ln0_stat[2]),
        .Customized_PHY_Top_q1_ln0_rx_cdr_lock_o(ln0_stat[1]), .Customized_PHY_Top_q1_ln0_pll_lock_o(ln0_stat[0]),
        .Customized_PHY_Top_q1_ln0_ready_o(ln0_stat[3]),
        .Customized_PHY_Top_q1_ln0_rx_clk_i(rxc0), .Customized_PHY_Top_q1_ln0_rx_fifo_rden_i(rd_en0),
        .Customized_PHY_Top_q1_ln0_tx_clk_i(sfp_txc), .Customized_PHY_Top_q1_ln0_tx_data_i({70'd0, t0}),
        .Customized_PHY_Top_q1_ln0_tx_fifo_wren_i(wr_en0),
        .Customized_PHY_Top_q1_ln0_pma_rstn_i(ln_rst_n[0]), .Customized_PHY_Top_q1_ln0_pcs_rx_rst_i(ln_rx_rst[0]),
        .Customized_PHY_Top_q1_ln0_pcs_tx_rst_i(ln_tx_rst[0]),
        // lane 1
        .Customized_PHY_Top_q1_ln1_rx_pcs_clkout_o(rxc1), .Customized_PHY_Top_q1_ln1_rx_data_o(rxd1),
        .Customized_PHY_Top_q1_ln1_rx_fifo_rdusewd_o(), .Customized_PHY_Top_q1_ln1_rx_fifo_aempty_o(rxae1),
        .Customized_PHY_Top_q1_ln1_rx_fifo_empty_o(), .Customized_PHY_Top_q1_ln1_rx_valid_o(rxv1),
        .Customized_PHY_Top_q1_ln1_tx_pcs_clkout_o(txc1), .Customized_PHY_Top_q1_ln1_tx_fifo_wrusewd_o(),
        .Customized_PHY_Top_q1_ln1_tx_fifo_afull_o(txaf1), .Customized_PHY_Top_q1_ln1_tx_fifo_full_o(),
        .Customized_PHY_Top_q1_ln1_refclk_o(), .Customized_PHY_Top_q1_ln1_signal_detect_o(ln1_stat[2]),
        .Customized_PHY_Top_q1_ln1_rx_cdr_lock_o(ln1_stat[1]), .Customized_PHY_Top_q1_ln1_pll_lock_o(ln1_stat[0]),
        .Customized_PHY_Top_q1_ln1_ready_o(ln1_stat[3]),
        .Customized_PHY_Top_q1_ln1_rx_clk_i(rxc1), .Customized_PHY_Top_q1_ln1_rx_fifo_rden_i(rd_en1),
        .Customized_PHY_Top_q1_ln1_tx_clk_i(bl_txc), .Customized_PHY_Top_q1_ln1_tx_data_i({60'd0, t1}),
        .Customized_PHY_Top_q1_ln1_tx_fifo_wren_i(wr_en1),
        .Customized_PHY_Top_q1_ln1_pma_rstn_i(ln_rst_n[1]), .Customized_PHY_Top_q1_ln1_pcs_rx_rst_i(ln_rx_rst[1]),
        .Customized_PHY_Top_q1_ln1_pcs_tx_rst_i(ln_tx_rst[1])
    );

endmodule
